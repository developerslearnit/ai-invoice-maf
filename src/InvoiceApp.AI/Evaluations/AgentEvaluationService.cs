using Microsoft.Extensions.Logging;

namespace InvoiceApp.AI.Evaluations;

/// <summary>
/// Defines evaluation contracts for auditing generated AI agent responses against enterprise compliance,
/// safety guidelines, and hallucination risks before returning them to callers.
/// </summary>
public interface IAgentEvaluationService
{
    /// <summary>
    /// Analyzes an agent's generated response against the user prompt, calculating a confidence score
    /// and checking for policy adherence or hallucination indicators.
    /// </summary>
    /// <param name="prompt">The original user prompt or instruction.</param>
    /// <param name="response">The textual reply generated by the autonomous agent or tool pipeline.</param>
    /// <param name="cancellationToken">A token to monitor for cancellation requests.</param>
    /// <returns>An evaluation summary result containing confidence metrics and policy checks.</returns>
    Task<AgentEvaluationResult> EvaluateResponseAsync(string prompt, string response, CancellationToken cancellationToken = default);
}

/// <summary>
/// Represents the evaluation outcome of an autonomous agent's generated response.
/// </summary>
/// <param name="ConfidenceScore">Normalized confidence rating between 0.0 (low) and 1.0 (high certainty).</param>
/// <param name="PassedPolicyCheck">Indicates whether the response meets enterprise privacy, safety, and operational policies.</param>
/// <param name="HasHallucinationRisk">Indicates whether linguistic or factual uncertainty patterns were identified.</param>
/// <param name="Feedback">Descriptive feedback describing why the evaluation passed or raised concerns.</param>
public sealed record AgentEvaluationResult(
    double ConfidenceScore,
    bool PassedPolicyCheck,
    bool HasHallucinationRisk,
    string Feedback
);

/// <summary>
/// Default heuristic implementation of <see cref="IAgentEvaluationService"/> providing automated policy
/// and hallucination guardrails for agent responses.
/// </summary>
/// <param name="logger">The structured logger instance.</param>
public sealed class AgentEvaluationService(ILogger<AgentEvaluationService> logger) : IAgentEvaluationService
{
    /// <inheritdoc />
    public Task<AgentEvaluationResult> EvaluateResponseAsync(string prompt, string response, CancellationToken cancellationToken = default)
    {
        bool hasHallucinationRisk = response.Contains("I am not sure", StringComparison.OrdinalIgnoreCase) || response.Length < 10;
        bool passedPolicy = !response.Contains("confidential_bypass", StringComparison.OrdinalIgnoreCase);

        logger.LogDebug("Evaluated response: PolicyPassed={Passed}, HallucinationRisk={Risk}", passedPolicy, hasHallucinationRisk);

        return Task.FromResult(new AgentEvaluationResult(
            ConfidenceScore: hasHallucinationRisk ? 0.65 : 0.95,
            PassedPolicyCheck: passedPolicy,
            HasHallucinationRisk: hasHallucinationRisk,
            Feedback: passedPolicy ? "Response complies with enterprise guidelines." : "Potential policy violation detected."
        ));
    }
}
