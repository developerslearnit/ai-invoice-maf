namespace InvoiceApp.Web.Models.ViewModels;

/// <summary>
/// Contextual metadata captured from the client browser and sent alongside AI chat requests.
/// </summary>
/// <param name="Page">The active page or view name (e.g. 'InvoiceDetails', 'CustomerDetails', 'Dashboard').</param>
/// <param name="InvoiceId">Optional active invoice GUID string.</param>
/// <param name="InvoiceNumber">Optional active invoice number (e.g. 'INV-000001').</param>
/// <param name="CustomerId">Optional active customer GUID string.</param>
/// <param name="CustomerName">Optional active customer name.</param>
public sealed record AiChatContext(
    string? Page = null,
    string? InvoiceId = null,
    string? InvoiceNumber = null,
    string? CustomerId = null,
    string? CustomerName = null);

/// <summary>
/// Represents a chat request initiated from the Web UI to the AI service.
/// </summary>
/// <param name="Message">The user prompt or command text.</param>
/// <param name="ConversationId">Optional conversation identifier.</param>
/// <param name="Context">Optional client-side state context.</param>
public sealed record AiChatRequest(
    string Message,
    string? ConversationId = null,
    AiChatContext? Context = null);

/// <summary>
/// Represents a structured chat response returned from the AI service to the Web UI.
/// </summary>
/// <param name="Message">The markdown-formatted response generated by the agent.</param>
/// <param name="ConversationId">The conversation session identifier.</param>
/// <param name="Suggestions">Optional contextual prompt chips.</param>
/// <param name="AgentName">Optional name of the executing agent.</param>
/// <param name="DurationMs">Optional execution latency in milliseconds.</param>
/// <param name="ConfidenceScore">Optional confidence score.</param>
/// <param name="IsSuccess">Indicates whether the request succeeded.</param>
public sealed record AiChatResponse(
    string Message,
    string ConversationId,
    IReadOnlyCollection<string>? Suggestions = null,
    string? AgentName = null,
    long? DurationMs = null,
    double? ConfidenceScore = null,
    bool IsSuccess = true);
